// Package config reads all settings from environment variables.
package config

import (
	"encoding/hex"
	"fmt"
	"os"
	"strconv"
	"time"
)

// Config for the API process. The simulator and verifier read their own few
// variables directly.
type Config struct {
	HTTPAddr        string
	DatabaseURL     string
	JWTSecret       []byte
	AccessTTL       time.Duration
	RefreshTTL      time.Duration
	DeviceKeyEncKey []byte // 32 bytes, encrypts device keys at rest
	ProvisionSecret []byte // derives device keys (demo provisioning)
	SignatureSkew   time.Duration
	CORSOrigin      string
	LogLevel        string
	RequestTimeout  time.Duration
	ShutdownTimeout time.Duration

	Seed         int64
	SensorCount  int
	BackfillHour int // hours of history generated by the seed

	RawRetention  time.Duration
	EvalInterval  time.Duration
	EscalateAfter time.Duration
	IngestFlush   time.Duration
}

// Load reads and validates the configuration.
func Load() (Config, error) {
	c := Config{
		HTTPAddr:        str("HTTP_ADDR", ":8080"),
		DatabaseURL:     str("DATABASE_URL", ""),
		JWTSecret:       []byte(str("JWT_SECRET", "")),
		AccessTTL:       dur("ACCESS_TOKEN_TTL", 15*time.Minute),
		RefreshTTL:      dur("REFRESH_TOKEN_TTL", 7*24*time.Hour),
		ProvisionSecret: []byte(str("DEVICE_PROVISION_SECRET", "")),
		SignatureSkew:   dur("DEVICE_SIGNATURE_SKEW", 2*time.Minute),
		CORSOrigin:      str("CORS_ORIGIN", "http://localhost:3000"),
		LogLevel:        str("LOG_LEVEL", "info"),
		RequestTimeout:  dur("REQUEST_TIMEOUT", 10*time.Second),
		ShutdownTimeout: dur("SHUTDOWN_TIMEOUT", 15*time.Second),
		Seed:            int64(num("SEED", 42)),
		SensorCount:     num("SENSOR_COUNT", 2000),
		BackfillHour:    num("BACKFILL_HOURS", 24),
		RawRetention:    dur("RAW_RETENTION", 7*24*time.Hour),
		EvalInterval:    dur("EVAL_INTERVAL", 30*time.Second),
		EscalateAfter:   dur("ESCALATE_AFTER", 10*time.Minute),
		IngestFlush:     dur("INGEST_FLUSH_INTERVAL", time.Second),
	}
	var err error
	if c.DeviceKeyEncKey, err = hex.DecodeString(str("DEVICE_KEY_ENC_KEY", "")); err != nil || len(c.DeviceKeyEncKey) != 32 {
		return c, fmt.Errorf("DEVICE_KEY_ENC_KEY must be 64 hex characters")
	}
	switch {
	case c.DatabaseURL == "":
		return c, fmt.Errorf("DATABASE_URL is required")
	case len(c.JWTSecret) < 32:
		return c, fmt.Errorf("JWT_SECRET must be at least 32 bytes")
	case len(c.ProvisionSecret) < 16:
		return c, fmt.Errorf("DEVICE_PROVISION_SECRET must be at least 16 bytes")
	}
	return c, nil
}

func str(k, def string) string {
	if v, ok := os.LookupEnv(k); ok && v != "" {
		return v
	}
	return def
}

func num(k string, def int) int {
	if v, err := strconv.Atoi(os.Getenv(k)); err == nil {
		return v
	}
	return def
}

func dur(k string, def time.Duration) time.Duration {
	if v, err := time.ParseDuration(os.Getenv(k)); err == nil {
		return v
	}
	return def
}
